namespace Len.StronglyTypedId;

/// <summary>
/// Supplies assembly-level defaults for <see cref="StronglyTypedIdAttribute"/>, removing the need to
/// repeat them on every type.
/// </summary>
[AttributeUsage(AttributeTargets.Assembly, Inherited = false, AllowMultiple = false)]
public class StronglyTypedIdDefaultsAttribute : Attribute
{
    /// <summary>
    /// Gets or sets the name of the validator method used by default for strongly typed ids in this
    /// assembly.
    /// </summary>
    public string? Validator { get; set; }

    /// <summary>
    /// Gets or sets the name of the normalizer method used by default for strongly typed ids in this
    /// assembly.
    /// </summary>
    public string? Normalizer { get; set; }

    /// <summary>
    /// Gets or sets the exception type thrown by default when validation fails for strongly typed ids in
    /// this assembly. The type must derive from <see cref="Exception"/>, must not be abstract, and must
    /// expose a constructor that takes a single <see cref="string"/> message.
    /// </summary>
    public Type? ExceptionType { get; set; }

    /// <summary>
    /// Gets or sets whether the rejected value is left out of the validation failure message by default
    /// for strongly typed ids in this assembly. The default is <see langword="false"/>, which keeps the
    /// value in the message.
    /// </summary>
    /// <remarks>
    /// The rejected value reaches logs and APM traces with the exception message; for a
    /// <see cref="string"/>-based id that text is user input. Use this property to redact a whole
    /// assembly; to redact a single id instead, write
    /// <see cref="StronglyTypedIdAttribute.RedactValidationMessage"/> on the type.
    /// </remarks>
    public bool RedactValidationMessage { get; set; }

    /// <summary>
    /// Gets or sets which integration code is generated by default for strongly typed ids in this
    /// assembly. The default is <see cref="StronglyTypedIdIntegrations.Default"/>, which means "generate
    /// whatever the compilation references".
    /// </summary>
    /// <remarks>
    /// A per-type <see cref="StronglyTypedIdAttribute.Integrations"/> overrides this setting unless it is
    /// <see cref="StronglyTypedIdIntegrations.Default"/>. To restore a single id after this property has
    /// switched integrations off, write <see cref="StronglyTypedIdIntegrations.All"/>.
    /// </remarks>
    public StronglyTypedIdIntegrations Integrations { get; set; }
}
