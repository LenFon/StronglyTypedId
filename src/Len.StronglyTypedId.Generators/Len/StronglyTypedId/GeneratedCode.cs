using System.Text;

namespace Len.StronglyTypedId;

/// <summary>
/// 生成代码时的文本工具。
/// </summary>
internal static class GeneratedCode
{
    /// <summary>
    /// 每个嵌套层级的缩进空格数。
    /// </summary>
    private const int IndentSize = 4;

    /// <summary>
    /// 写入 <c>GeneratedCodeAttribute</c> 的生成器版本。
    /// </summary>
    /// <remarks>
    /// 提到这里是因为 <see cref="StronglyTypedIdInfo"/> 也要渲染带该特性的成员，而它只能持有已渲染好的文本。
    /// </remarks>
    internal static readonly string Version = System.Reflection.Assembly.GetExecutingAssembly().GetName().Version.ToString(3);

    /// <summary>
    /// 把 <paramref name="code"/> 的换行符统一为 CRLF（模板源码自身的风格）。
    /// </summary>
    /// <remarks>
    /// 输入里没有 <c>'\r'</c> 时说明全是 LF，保持原样。模板来自 CRLF 源文件，这条分支实际不可达，保留只为不改写纯 LF 输入。
    /// </remarks>
    public static string NormalizeLineEndings(string code)
        => code.IndexOf('\r') >= 0
            ? code.Replace("\r\n", "\n").Replace("\n", "\r\n")
            : code;

    /// <summary>
    /// 把生成好的源码按统一行尾写入编译单元，hint 名即产物文件名。
    /// </summary>
    /// <remarks>
    /// 各生成器都走这一条路径，行尾归一化不会漏掉某一处。
    /// </remarks>
    public static void AddGeneratedSource(SourceProductionContext context, string hintName, string code)
        => context.AddSource(hintName, NormalizeLineEndings(code));

    /// <summary>
    /// 生成代码里引用不变文化的完整表达式。
    /// </summary>
    /// <remarks>
    /// 解析与格式化一律与区域性无关，各集成生成器共用同一份文本，避免逐处手写而漂移。
    /// </remarks>
    public const string InvariantCulture = "global::System.Globalization.CultureInfo.InvariantCulture";

    /// <summary>
    /// 产物里用到 <c>System.MemoryExtensions</c> 的扩展方法（<c>StartsWith</c> / <c>AsSpan</c> / <c>AsMemory</c>）
    /// 时，文件头必须补的 using。
    /// </summary>
    /// <remarks>
    /// 必须带 <c>global::</c>：产物声明在 Id 自己的命名空间下，裸 <c>using System;</c> 会先在同级命名空间里
    /// 找 <c>Xxx.System</c>，找到就遮蔽 BCL 的 <c>System</c>（实测 <c>CS0246: 未能找到类型或命名空间名
    /// "ReadOnlySpan&lt;&gt;"</c>）。<c>global::</c> 强制从全局命名空间起解析，绕开这条规则。
    /// <para>
    /// 不要「简化」成 <c>using System;</c>：只有消费方恰好没有同级 <c>System</c> 命名空间时才碰巧能编译。
    /// </para>
    /// </remarks>
    public const string SystemUsing = "using global::System;";

    /// <summary>
    /// 各生成器产出的源文件统一文件头：<c>// &lt;auto-generated /&gt;</c> 注释、命名空间声明与
    /// <c>#nullable enable</c>，并以两个空行收尾，便于直接拼接类型声明块。
    /// </summary>
    public static string Header(string namespaceName, string? preamble = null)
    {
        var builder = new StringBuilder();

        builder.Append("// <auto-generated />\n\n");

        if (!string.IsNullOrEmpty(preamble))
        {
            builder.Append(preamble).Append("\n\n");
        }

        builder.Append("namespace ").Append(namespaceName).Append(";\n\n#nullable enable\n\n");

        return builder.ToString();
    }

    /// <summary>
    /// 标记成员由源生成器生成的 <c>[CompilerGenerated]</c> 特性文本（不含缩进、不含行尾）。
    /// </summary>
    public const string CompilerGeneratedAttribute = "[global::System.Runtime.CompilerServices.CompilerGeneratedAttribute]";

    /// <summary>
    /// 取单个 <c>[GeneratedCode("生成器名", "版本")]</c> 特性文本（不含缩进、不含行尾）。
    /// </summary>
    public static string GeneratedCodeAttribute(string generatorName, string version)
        => $"[global::System.CodeDom.Compiler.GeneratedCodeAttribute(\"{generatorName}\", \"{version}\")]";

    /// <summary>
    /// 把 <c>[Flags]</c> 枚举的「未定义位掩码」渲染成 C# 字面量。
    /// </summary>
    /// <remarks>
    /// 定长十六进制而非十进制：掩码常常接近满位，十进制既难核对又容易数错位数。
    /// </remarks>
    public static string UndefinedBitsLiteral(ulong mask)
        => "0x" + mask.ToString("X16", System.Globalization.CultureInfo.InvariantCulture) + "UL";

    /// <summary>
    /// 把在命名空间层级书写的强类型 Id 声明块嵌进各层包含类型里，并按嵌套层数整体缩进。
    /// </summary>
    public static string NestInContainingTypes(StronglyTypedIdInfo idInfo, string declarationBlock)
    {
        if (idInfo.NestingDepth == 0)
        {
            return declarationBlock;
        }

        var declarations = idInfo.ContainingTypeDeclarations.Split('\n');
        var bodyIndent = new string(' ', declarations.Length * IndentSize);
        var lines = new List<string>();

        for (var depth = 0; depth < declarations.Length; depth++)
        {
            var indent = new string(' ', depth * IndentSize);

            lines.Add(indent + declarations[depth]);
            lines.Add(indent + "{");
        }

        foreach (var line in declarationBlock.Split('\n'))
        {
            lines.Add(line.Length == 0 ? line : bodyIndent + line);
        }

        for (var depth = declarations.Length - 1; depth >= 0; depth--)
        {
            lines.Add(new string(' ', depth * IndentSize) + "}");
        }

        return string.Join("\n", lines);
    }
}
