using System.Text;

namespace Len.StronglyTypedId;

/// <summary>
/// 生成代码时的文本工具。
/// </summary>
internal static class GeneratedCode
{
    /// <summary>
    /// 每个嵌套层级的缩进空格数。
    /// </summary>
    private const int IndentSize = 4;

    /// <summary>
    /// 把 <paramref name="code"/> 的换行符统一为模板自身使用的风格。
    /// </summary>
    /// <remarks>
    /// <para>
    /// 生成模板是原始字符串字面量，其行尾即源文件的行尾 —— 随 git 的 <c>text=auto</c> 在 CRLF（Windows 工作区）
    /// 与 LF（Linux / macOS 检出）之间变化；而按条件拼出的片段一律以 <c>\n</c> 书写。两者直接相接会让同一个
    /// 生成文件出现混排行尾：既破坏确定性构建，也让快照断言隐含依赖平台。
    /// </para>
    /// <para>
    /// 判据取「模板里是否出现过 <c>\r</c>」，而不是 <see cref="System.Environment.NewLine"/>：
    /// 后者是运行生成器的机器属性，与模板所在文件的行尾并无必然关系。
    /// </para>
    /// </remarks>
    public static string NormalizeLineEndings(string code)
        => code.IndexOf('\r') >= 0
            ? code.Replace("\r\n", "\n").Replace("\n", "\r\n")
            : code.Replace("\r\n", "\n");

    /// <summary>
    /// 各生成器产出的源文件统一文件头：<c>// &lt;auto-generated /&gt;</c> 注释、命名空间声明与
    /// <c>#nullable enable</c>，并以两个空行收尾，便于直接拼接类型声明块。
    /// </summary>
    /// <param name="namespaceName">生成代码所在命名空间。</param>
    /// <param name="preamble">
    /// 可选的前导段（如 Swagger 生成器需要的 <c>using Microsoft.Extensions.DependencyInjection;</c>），
    /// 置于 <c>// &lt;auto-generated /&gt;</c> 与命名空间声明之间；为空时省略。
    /// </param>
    /// <remarks>
    /// 行尾统一用 <c>\r\n</c>：仓库源文件为 CRLF，且未走 <see cref="NormalizeLineEndings"/> 的集成生成器
    /// 直接以该字符串拼接原始字符串字面量，用 CRLF 才能与字面量自身的 CRLF 行尾保持一致，避免混排行尾。
    /// </remarks>
    public static string Header(string namespaceName, string? preamble = null)
    {
        var builder = new StringBuilder();

        builder.Append("// <auto-generated />\r\n\r\n");

        if (!string.IsNullOrEmpty(preamble))
        {
            builder.Append(preamble).Append("\r\n\r\n");
        }

        builder.Append("namespace ").Append(namespaceName).Append(";\r\n\r\n#nullable enable\r\n\r\n");

        return builder.ToString();
    }

    /// <summary>
    /// 标记成员由源生成器生成的 <c>[CompilerGenerated]</c> 特性文本（不含缩进、不含行尾）。
    /// </summary>
    /// <remarks>各生成器模板里逐字重复的完全限定名集中在此，避免拼写漂移。</remarks>
    public const string CompilerGeneratedAttribute = "[global::System.Runtime.CompilerServices.CompilerGeneratedAttribute]";

    /// <summary>
    /// 取单个 <c>[GeneratedCode("生成器名", "版本")]</c> 特性文本（不含缩进、不含行尾）。
    /// </summary>
    /// <param name="generatorName">生成器类名（通常传 <c>nameof(生成器)</c>）。</param>
    /// <param name="version">写入特性的生成器版本。</param>
    public static string GeneratedCodeAttribute(string generatorName, string version)
        => $"[global::System.CodeDom.Compiler.GeneratedCodeAttribute(\"{generatorName}\", \"{version}\")]";

    /// <summary>
    /// 把在命名空间层级书写的强类型 Id 声明块嵌进各层包含类型里，并按嵌套层数整体缩进。
    /// </summary>
    /// <param name="idInfo">强类型 Id 描述，提供包含类型链。</param>
    /// <param name="declarationBlock">
    /// 自 <c>partial record …</c> 起、到该类型自身的收尾大括号为止的声明块，书写在 0 缩进处；
    /// 附在 Id 上的特性（如 <c>[JsonConverter]</c>）属于签名的一部分，一并含在其中。
    /// </param>
    /// <remarks>
    /// <para>
    /// partial 类型的各段必须处在同一容器内，所以嵌套类型的强类型 Id 无法像顶层类型那样在命名空间层级
    /// 补成员，只能把声明逐层放回原本的包含类型中。顶层类型（<see cref="StronglyTypedIdInfo.NestingDepth"/>
    /// 为 0）原样返回，产物与不支持嵌套时的逐字节一致 —— 既有快照即回归基线。
    /// </para>
    /// <para>
    /// 行尾一律用 <c>\n</c> 拼接，由调用方在最后统一交给 <see cref="NormalizeLineEndings"/>；
    /// 缩进逐行显式写出，不依赖原始字符串字面量的裁剪规则。空行保持为空，不补缩进，
    /// 以免在产物里留下行尾空白。
    /// </para>
    /// </remarks>
    public static string NestInContainingTypes(StronglyTypedIdInfo idInfo, string declarationBlock)
    {
        if (idInfo.NestingDepth == 0)
        {
            return declarationBlock;
        }

        var declarations = idInfo.ContainingTypeDeclarations.Split('\n');
        var bodyIndent = new string(' ', declarations.Length * IndentSize);
        var lines = new List<string>();

        for (var depth = 0; depth < declarations.Length; depth++)
        {
            var indent = new string(' ', depth * IndentSize);

            lines.Add(indent + declarations[depth]);
            lines.Add(indent + "{");
        }

        foreach (var line in declarationBlock.Split('\n'))
        {
            lines.Add(line.Length == 0 ? line : bodyIndent + line);
        }

        for (var depth = declarations.Length - 1; depth >= 0; depth--)
        {
            lines.Add(new string(' ', depth * IndentSize) + "}");
        }

        return string.Join("\n", lines);
    }
}
