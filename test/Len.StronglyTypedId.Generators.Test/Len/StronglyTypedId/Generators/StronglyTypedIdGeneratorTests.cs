                public partial record struct OrderId(Guid Value);
            }

            public partial struct ShipmentBatch
            {
                [StronglyTypedId]
                public partial record OrderId(Guid Value);
            }

            public partial record Inventory(Guid WarehouseId)
            {
                [StronglyTypedId]
                public partial record struct SkuId(string Value);

                public partial class Bin
                {
                    [StronglyTypedId]
                    public partial record struct SkuId(int Value);
                }
            }

            public partial interface IShipment
            {
                [StronglyTypedId]
                public partial record struct BatchId(Guid Value);
            }

            public class TestDbContext : DbContext
            {
                protected override void ConfigureConventions(ModelConfigurationBuilder configurationBuilder) { }
            }
            """;

        var compilation = CreateCompilation(
            code,
            [typeof(Microsoft.EntityFrameworkCore.DbContext), typeof(Swashbuckle.AspNetCore.SwaggerGen.SwaggerGenOptions)],
            [
                AssemblyReferenceCache.FromAssembly(typeof(Microsoft.OpenApi.Models.OpenApiSchema).Assembly),
                AssemblyReferenceCache.FromAssembly(typeof(Microsoft.Extensions.DependencyInjection.IServiceCollection).Assembly),
                // EF Core 的 ValueConverter 签名里带 Expression<>，而合成编译的引用集由 AppDomain 里「已加载」的
                // 程序集拼出（见 ShouldReferenceAssembly），单跑本用例时它可能尚未加载 —— 显式引入，让结果与运行顺序无关。
                AssemblyReferenceCache.FromAssembly(typeof(System.Linq.Expressions.Expression).Assembly),
            ]);

        var cancellationToken = TestContext.Current.CancellationToken;

        var driver = CSharpGeneratorDriver
            .Create(new StronglyTypedIdGenerator())
            .RunGeneratorsAndUpdateCompilation(compilation, out var outputCompilation, out var generatorDiagnostics, cancellationToken);

        var generatorErrors = generatorDiagnostics.Where(d => d.Severity == DiagnosticSeverity.Error).ToArray();

        generatorErrors.Should().BeEmpty(string.Join("\n", generatorErrors.Select(error => error.ToString())));

        // 产物必须逐个落到位：嵌套包装若整段失效，Emit 照样会成功（类型自身的声明本就合法），
        // 只有 hint 名与生成成员一起断言才能发现「声明被写到了容器外」。
        var hintNames = driver.GetRunResult().Results[0].GeneratedSources
            .Select(source => source.HintName)
            .ToArray();

        hintNames.Should().Contain(
        [
            "Len.StronglyTypedId.OrderAggregate.OrderId.g.cs",
            "Len.StronglyTypedId.ShipmentBatch.OrderId.g.cs",
            "Len.StronglyTypedId.Inventory.SkuId.g.cs",
            "Len.StronglyTypedId.Inventory.Bin.SkuId.g.cs",
            // 接口容器：README 把 interface 与 class/struct/record 并列为受支持的容器，这里用真实编译背书。
            "Len.StronglyTypedId.IShipment.BatchId.g.cs",
        ]);

        using var stream = new MemoryStream();
        var emit = outputCompilation.Emit(stream, cancellationToken: cancellationToken);

        // 程序集统一性告警（CS1701/CS1702）来自合成编译拼装引用程序集的方式，与被测产物无关，
        // 与既有 Emit 用例保持同一口径排除。
        var failures = emit.Diagnostics
            .Where(diagnostic => diagnostic.Severity >= DiagnosticSeverity.Warning)
            .Where(diagnostic => diagnostic.Id is not ("CS1701" or "CS1702"))
            .ToArray();

        failures.Should().BeEmpty(string.Join("\n", failures.Select(failure => failure.ToString())));
    }

