                AssemblyReferenceCache.FromAssembly(typeof(StronglyTypedIdAttribute).Assembly),
            ],
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));

        return compilation.ToMetadataReference();
    }

